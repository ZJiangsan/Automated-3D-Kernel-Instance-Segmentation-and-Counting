"""Generate RGB-only COB-1 exporter from a verified Windows density exporter.

Requires `export_cob1_density_windows.py` (generated by the density
sensitivity package) in the home directory. This is an *exploratory*
non-validated baseline, not the manuscript's original SEG pipeline.
"""
from pathlib import Path

folder = Path.home()
source = folder / 'export_cob1_density_windows.py'
destination = folder / 'export_rgb_cob1.py'
if not source.exists():
    raise FileNotFoundError(f'Previously successful COB-1 exporter not found: {source}')
s = source.read_text(encoding='utf-8')
changes = [
    ('f"best_checkpoint_nerfacto_cobNew{folder_i}Seg_RGB_pc_001.pth"',
     'f"best_checkpoint_nerfacto_cobNew{folder_i}_RGB_pc_001.pth"'),
    ('outdir = base / "density_sensitivity_windows" / folder_i',
     'outdir = base / "direct_rgb_3d" / folder_i'),
    ('thresholds = (40, 50, 60, 70, 80, 90, 100)',
     'thresholds = (70,)'),
    ('f"{folder_i}SEG_density_pc_001_threshold_{t:03d}.ply"',
     'f"{folder_i}_RGB_only_density{t}.ply"'),
    ('COB-1 EXPORT COMPLETE. Original .ply unchanged.',
     'COB-1 RGB-ONLY EXPORT COMPLETE. Segmentation checkpoint not used.'),
]
for old, new in changes:
    count = s.count(old)
    if count != 1:
        raise RuntimeError(f'Expected exactly one occurrence ({count}) of {old!r}; original script changed')
    s = s.replace(old, new)
if 'f"best_checkpoint_nerfacto_cobNew{folder_i}Seg_RGB_pc_001.pth"' in s:
    raise RuntimeError('Failed to replace SEG checkpoint')
compile(s, str(destination), 'exec')
destination.write_text(s, encoding='utf-8')
print('Created:', destination)
print('RGB-only checkpoint expected under the base dataset folder:')
print('  best_checkpoint_nerfacto_cobNewcob1_out_RGB_pc_001.pth')
print('If your checkpoint is stored elsewhere, modify the generated script checkpoint path.')
print('Next run:', destination)
print('Then run:', folder / 'direct_rgb_maize_count_v2.py')
